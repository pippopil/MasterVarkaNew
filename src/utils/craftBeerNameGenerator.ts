/**
 * Хранилище сгенерированных за сессию названий для исключения повторений
 */
const sessionUsedNames = new Set<string>();

export function clearSessionUsedNames(): void {
  sessionUsedNames.clear();
}

/**
 * Генерация партии оригинальных концептов пива с гарантией отсутствия повторов
 */
export function generateBeerConcepts(
  recipe: Recipe,
  options: {
    archetype: NameArchetype;
    mood?: NameMood;
    count?: number;
  }
): GeneratedBeerConcept[] {
  const { archetype = 'all', mood = 'bold', count = 6 } = options;

  const validArchetypes: Exclude<NameArchetype, 'all'>[] =
    archetype === 'all'
      ? ['craft_puns', 'slavic_myth', 'nordic_saga', 'cyber_scifi', 'monastery_classic', 'rock_rebel', 'taiga_wild']
      : [archetype];

  const results: GeneratedBeerConcept[] = [];
  const abv = Number(recipe.calculated?.abv || 5.0).toFixed(1);
  const ibu = Math.round(Number(recipe.calculated?.ibu || 30));
  const style = recipe.style || 'Крафтовое пиво';

  // Если сессионная память превысила 300 названий — очищаем, чтобы не блокировать выбор
  if (sessionUsedNames.size > 300) {
    sessionUsedNames.clear();
  }

  const batchUsedNames = new Set<string>();

  for (let i = 0; i < count; i++) {
    const chosenArchetype = pick(validArchetypes);
    const db = DATABASE[chosenArchetype];
    const meta = ARCHETYPES_META.find(m => m.id === chosenArchetype)!;

    // Ищем уникальное имя среди базы и динамических генераций
    let candidateName = '';
    let attempts = 0;

    while (attempts < 40) {
      // 50% шанс взять авторское имя из базы, 50% сформировать комбинацию (Прилагательное + Существительное)
      if (Math.random() > 0.5 && db.adjectives && db.nouns) {
        const adj = pick(db.adjectives);
        const noun = pick(db.nouns);
        candidateName = `${adj} ${noun}`;
      } else {
        candidateName = pick(db.names);
      }

      if (!batchUsedNames.has(candidateName) && !sessionUsedNames.has(candidateName)) {
        break;
      }
      attempts++;
    }

    // Если все варианты в сессии исчерпаны, берем любое уникальное в текущей пачке
    if (batchUsedNames.has(candidateName) || !candidateName) {
      candidateName = pick(db.names);
    }

    batchUsedNames.add(candidateName);
    sessionUsedNames.add(candidateName);

    const slogan = pick(db.slogans);
    const legend = pick(db.legends);

    const backLabelDescription = `Сварено по авторскому рецепту в стиле ${style}. Начальная плотность сусла обеспечивает баланс, а выверенная крепость ${abv}% и горечь ${ibu} IBU раскрываются богатым вкусовым букетом. Рекомендуется подавать при температуре 8–11°C. Состав: чистая подготовленная вода, солод ячменный, отборный хмель, пивоваренные дрожжи. Нефильтрованное, непастеризованное.`;

    results.push({
      id: `concept_${Date.now()}_${i}_${Math.random().toString(36).substring(2, 6)}`,
      name: candidateName,
      slogan,
      legend,
      backLabelDescription,
      archetype: chosenArchetype,
      archetypeName: meta.label.split(' ')[1] || meta.label,
      mood: mood,
      themeStyle: db.theme,
      suggestedArtwork: db.artwork,
      backgroundTexture: db.backgroundTexture,
      suggestedBacking: db.suggestedBacking,
      palette: db.palette
    });
  }

  return results;
}
